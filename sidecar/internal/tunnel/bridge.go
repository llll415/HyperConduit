package tunnel

import (
	"context"
	"encoding/binary"
	"encoding/hex"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"net"
	"net/netip"
	"strconv"
	"time"

	"github.com/apernet/hysteria/core/v2/observe"
)

const (
	// bridgeMagic identifies the private-Minecraft bridge preface. It is ASCII
	// so packet captures and protocol tests remain readable.
	bridgeMagic = "HCMETA01"

	// bridgeMaxJSONSize bounds the metadata that follows the length prefix.
	bridgeMaxJSONSize = 1024

	// bridgeTokenLength is the number of hexadecimal characters in a token
	// derived from 32 random bytes by the Java control plane.
	bridgeTokenLength = 64

	// bridgeWriteWindow bounds preface writes when the caller supplied no
	// deadline. The stream/request timeout remains the normal upper bound.
	bridgeWriteWindow = 5 * time.Second
)

var (
	errBridgeToken    = errors.New("bridge preface: invalid token")
	errBridgeIdentity = errors.New("bridge preface: invalid stream identity")
	errBridgePeer     = errors.New("bridge preface: invalid peer address")
	errBridgeTooLarge = errors.New("bridge preface: metadata too large")
)

// bridgeMetadata is the JSON body of the server-to-private-Minecraft preface.
// The token is a per-listener bridge secret generated by the Java control
// plane; it is not the player's Hysteria token.
type bridgeMetadata struct {
	Token        string `json:"token"`
	Peer         string `json:"peer"`
	ConnectionID uint64 `json:"connectionId"`
	StreamID     int64  `json:"streamId"`
}

// writeBridgePreface writes the optional preface to the private Minecraft TCP
// connection before any Minecraft bytes are forwarded:
//
//	"HCMETA01" | uint32 big-endian JSON length | JSON metadata
//
// An empty token means the standalone deployment is in use, so nothing is
// written and the original target keeps working. A non-empty token must be 64
// hexadecimal characters (32 bytes) and is never included in returned errors.
//
// The metadata is taken only from trusted server-side observations:
// ConnectionID must be non-zero, StreamID must be non-negative, and Peer must
// be a literal IP:port (no DNS resolution). Invalid observations are rejected
// before any bytes are written.
//
// The write is bounded by ctx's deadline, or a five-second fallback. Cancelling
// ctx interrupts a blocked write by installing an immediate write deadline; the
// cancellation callback is joined before the deadline is cleared so it cannot
// race with the connection being handed to the normal copy loop.
func writeBridgePreface(ctx context.Context, conn net.Conn, token string, info observe.StreamContext) error {
	if token == "" {
		return nil
	}
	if conn == nil {
		return errors.New("bridge preface: nil connection")
	}
	if ctx == nil {
		ctx = context.Background()
	}
	if err := validateBridgeToken(token); err != nil {
		return err
	}
	if err := validateBridgeStreamContext(info); err != nil {
		return err
	}
	payload, err := json.Marshal(bridgeMetadata{
		Token:        token,
		Peer:         info.RemoteAddr,
		ConnectionID: info.ConnectionID,
		StreamID:     info.StreamID,
	})
	if err != nil {
		return fmt.Errorf("bridge preface: encode metadata: %w", err)
	}
	if len(payload) > bridgeMaxJSONSize {
		return errBridgeTooLarge
	}
	if err := ctx.Err(); err != nil {
		return err
	}

	deadline, ok := ctx.Deadline()
	if !ok {
		deadline = time.Now().Add(bridgeWriteWindow)
	}
	if err := conn.SetWriteDeadline(deadline); err != nil {
		return fmt.Errorf("bridge preface: set write deadline: %w", err)
	}

	canceled := make(chan struct{})
	stopCancel := context.AfterFunc(ctx, func() {
		defer close(canceled)
		_ = conn.SetWriteDeadline(time.Now())
	})
	defer func() {
		// Join the callback before clearing the deadline. Otherwise a callback
		// that started just as the write finished could install a past deadline
		// after the connection was handed to the bridge copy loop.
		if !stopCancel() {
			<-canceled
		}
		_ = conn.SetWriteDeadline(time.Time{})
	}()

	frame := make([]byte, 0, len(bridgeMagic)+4+len(payload))
	frame = append(frame, bridgeMagic...)
	var size [4]byte
	binary.BigEndian.PutUint32(size[:], uint32(len(payload)))
	frame = append(frame, size[:]...)
	frame = append(frame, payload...)

	if err := writeBridgeAll(conn, frame); err != nil {
		if ctxErr := ctx.Err(); ctxErr != nil {
			return ctxErr
		}
		// The connection deadline and the context deadline may fire at the same
		// instant; the write can observe the timeout before ctx.Err() is set.
		if deadline, ok := ctx.Deadline(); ok && !time.Now().Before(deadline) {
			return context.DeadlineExceeded
		}
		return fmt.Errorf("bridge preface: write: %w", err)
	}
	return nil
}

// validateBridgeToken requires exactly 32 bytes encoded as 64 hex characters.
// The decoded bytes are not retained; the original text is forwarded verbatim.
func validateBridgeToken(token string) error {
	if len(token) != bridgeTokenLength {
		return errBridgeToken
	}
	if _, err := hex.DecodeString(token); err != nil {
		return errBridgeToken
	}
	return nil
}

// validateBridgeStreamContext rejects observations that cannot have come from
// the authenticated server-side core.
func validateBridgeStreamContext(info observe.StreamContext) error {
	if info.ConnectionID == 0 {
		return errBridgeIdentity
	}
	if info.StreamID < 0 {
		return errBridgeIdentity
	}
	return validateBridgePeer(info.RemoteAddr)
}

// validateBridgePeer accepts only a literal IP address with a numeric port in
// the range 1..65535. netip.ParseAddr never performs DNS resolution, so a peer
// such as "localhost:25565" is rejected.
func validateBridgePeer(peer string) error {
	host, port, err := net.SplitHostPort(peer)
	if err != nil {
		return errBridgePeer
	}
	ip, err := netip.ParseAddr(host)
	if err != nil || ip.IsUnspecified() {
		return errBridgePeer
	}
	if !validBridgePort(port) {
		return errBridgePeer
	}
	return nil
}

func validBridgePort(port string) bool {
	if port == "" {
		return false
	}
	for i := 0; i < len(port); i++ {
		if port[i] < '0' || port[i] > '9' {
			return false
		}
	}
	n, err := strconv.Atoi(port)
	return err == nil && n >= 1 && n <= 65535
}

// writeBridgeAll handles short writes without relying on WriterTo/ReaderFrom
// optimizations. A writer that returns (0, nil) is treated as a short write so
// the preface can never loop forever.
func writeBridgeAll(w io.Writer, p []byte) error {
	for len(p) > 0 {
		n, err := w.Write(p)
		if n < 0 || n > len(p) {
			return io.ErrShortWrite
		}
		p = p[n:]
		if err != nil {
			return err
		}
		if n == 0 {
			return io.ErrShortWrite
		}
	}
	return nil
}
