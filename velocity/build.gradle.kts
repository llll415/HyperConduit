import org.gradle.jvm.tasks.Jar
import java.util.zip.ZipFile
import java.security.MessageDigest

plugins {
    `java-library`
}

repositories {
    maven("https://repo.papermc.io/repository/maven-public/")
}

dependencies {
    // Velocity provides Gson, SLF4J, Adventure, Brigadier and Netty at runtime. None of these
    // dependencies are packaged into the plugin jar.
    compileOnly("com.velocitypowered:velocity-api:3.4.0-SNAPSHOT")
    annotationProcessor("com.velocitypowered:velocity-api:3.4.0-SNAPSHOT")
    compileOnly("com.google.code.gson:gson:2.10.1")
    compileOnly("org.slf4j:slf4j-api:2.0.16")

    // The runtime classes are bundled by unpacking the runtime jar below, so the plugin is a
    // single self-contained artifact apart from the Velocity-provided libraries.
    implementation(project(":sidecar-runtime"))

    // Test-only: main sources reference the Velocity API and Gson, so both must be visible while
    // compiling and running tests. They are still not packaged into the plugin jar.
    testImplementation("com.velocitypowered:velocity-api:3.4.0-SNAPSHOT")
    testImplementation("com.google.code.gson:gson:2.10.1")
    testImplementation("org.slf4j:slf4j-api:2.0.16")
}

val runtimeJar = project(":sidecar-runtime").tasks.named<Jar>("jar")

tasks.named<Jar>("jar") {
    archiveBaseName.set("hyperconduit-velocity")
    isPreserveFileTimestamps = false
    isReproducibleFileOrder = true

    dependsOn(runtimeJar)
    // Unpack the runtime jar (classes, five-platform sidecar binaries, manifests and third-party
    // notices) so Velocity sees one plugin artifact. Excluding the nested manifest keeps this
    // project's own manifest.
    from({ zipTree(runtimeJar.get().archiveFile.get().asFile) }) {
        exclude("META-INF/MANIFEST.MF")
        exclude("META-INF/*.SF", "META-INF/*.DSA", "META-INF/*.RSA")
    }
    from(rootProject.file("LICENSE")) { into("META-INF") }

    duplicatesStrategy = DuplicatesStrategy.EXCLUDE
}

val verifyVelocityJar by tasks.registering {
    group = "verification"
    description = "Verifies the Velocity plugin metadata, bundled runtime matrix and absent API classes."
    dependsOn(tasks.named("jar"))

    doLast {
        val artifact = tasks.named<Jar>("jar").get().archiveFile.get().asFile
        ZipFile(artifact).use { zip ->
            val pluginMetadata = zip.getEntry("velocity-plugin.json")
                ?: error("Missing velocity-plugin.json generated by the Velocity annotation processor")
            val metadata = zip.getInputStream(pluginMetadata).bufferedReader(Charsets.UTF_8).use {
                groovy.json.JsonSlurper().parse(it) as Map<*, *>
            }
            check(metadata["id"] == "hyperconduit") { "Unexpected Velocity plugin id: ${metadata["id"]}" }
            check(metadata["version"] == project.version.toString()) {
                "Velocity plugin version ${metadata["version"]} does not match ${project.version}"
            }

            val platforms = listOf("windows-amd64", "linux-amd64", "linux-arm64", "darwin-amd64", "darwin-arm64")
            for (platform in platforms) {
                val root = "io/hyperconduit/sidecar/bin/$platform/"
                val program = "hyperconduit-tunnel" + if (platform.startsWith("windows")) ".exe" else ""
                val manifestEntry = zip.getEntry(root + "manifest.json")
                    ?: error("Missing bundled sidecar manifest: $platform")
                val manifest = zip.getInputStream(manifestEntry).bufferedReader(Charsets.UTF_8).use {
                    groovy.json.JsonSlurper().parse(it) as Map<*, *>
                }
                check(manifest["file"] == program) { "Invalid sidecar manifest file for $platform" }
                val binary = zip.getEntry(root + program) ?: error("Missing bundled sidecar binary: $platform")
                check(binary.size in 1..(64L * 1024 * 1024)) { "Invalid binary size: $platform" }
                val digest = MessageDigest.getInstance("SHA-256")
                zip.getInputStream(binary).use { input ->
                    val buffer = ByteArray(64 * 1024)
                    while (true) {
                        val count = input.read(buffer)
                        if (count < 0) break
                        digest.update(buffer, 0, count)
                    }
                }
                val hash = digest.digest().joinToString("") { "%02x".format(it) }
                check(manifest["sha256"] == hash) { "Packaged binary hash mismatch: $platform" }
                check(manifest["protocolVersion"] == 1) { "Invalid protocol version: $platform" }
            }

            val bundled = zip.entries().asSequence()
                .map { it.name }
                .filter { it.startsWith("io/hyperconduit/sidecar/bin/") && !it.endsWith("/") }
                .toSet()
            check(bundled.size == platforms.size * 2) {
                "Unexpected or stale sidecar bundle entries: $bundled"
            }

            for (notice in listOf("GO-LICENSE", "HY2-LICENSE.md", "THIRD_PARTY_NOTICES.md")) {
                check(zip.getEntry("META-INF/hyperconduit-sidecar/$notice") != null) {
                    "Missing bundled notice: $notice"
                }
            }
            check(zip.getEntry("META-INF/LICENSE") != null) { "Missing project LICENSE" }

            // Velocity supplies these APIs. Packaging them would shadow the proxy's own copies.
            val forbidden = zip.entries().asSequence().map { it.name }.filter { name ->
                name.startsWith("com/velocitypowered/")
                        || name.startsWith("com/google/gson/")
                        || name.startsWith("org/slf4j/")
            }.toList()
            check(forbidden.isEmpty()) { "Plugin jar must not bundle Velocity-provided libraries: $forbidden" }
        }
    }
}

tasks.named("check") {
    dependsOn(verifyVelocityJar)
}
